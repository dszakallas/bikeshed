#!/usr/bin/env bash
export LC_ALL=C

base_spec="${1:-${BIKESHED_AGENTS_BASE_SPEC:-}}"
overrides_dir="${2:-${BIKESHED_AGENTS_OVERRIDES_DIR:-${CODEBOX_INIT_DIR:-}}}"
home_dir="${HOME:?HOME must be set}"
api_version="bikeshed.szakallas.net/v1alpha1"

log() { echo "activate-agent-configuration: $*" >&2; }

files=()

# 1. Base spec file from Nix store (or directory)
if [ -n "$base_spec" ]; then
  case "$base_spec" in
    /*) abs_base="$base_spec" ;;
    *)  abs_base="$home_dir/$base_spec" ;;
  esac
  if [ -f "$abs_base" ]; then
    files+=("$abs_base")
  elif [ -d "$abs_base" ]; then
    for f in "$abs_base"/*.yaml "$abs_base"/*.yml; do
      if [ -f "$f" ]; then files+=("$f"); fi
    done
  else
    log "base spec '$base_spec' not found"
  fi
fi

# 2. User-supplied overrides directory (supports colon-separated paths)
if [ -n "$overrides_dir" ]; then
  IFS=':' read -ra dirs <<< "$overrides_dir"
  for d in "${dirs[@]}"; do
    case "$d" in
      /*) abs_overrides="$d" ;;
      *)  abs_overrides="$home_dir/$d" ;;
    esac
    if [ -d "$abs_overrides" ]; then
      for f in "$abs_overrides"/*.yaml "$abs_overrides"/*.yml; do
        if [ -f "$f" ]; then files+=("$f"); fi
      done
    fi
  done
fi

# 3. Fallback: if no base_spec and no overrides_dir given, check default CODEBOX_INIT_DIR or /etc/bikeshed/agents/init
if [ "${#files[@]}" -eq 0 ] && [ -z "$base_spec" ] && [ -z "$overrides_dir" ]; then
  fallback_dir="${CODEBOX_INIT_DIR:-/etc/bikeshed/agents/init}"
  if [ -d "$fallback_dir" ]; then
    for f in "$fallback_dir"/*.yaml "$fallback_dir"/*.yml; do
      if [ -f "$f" ]; then files+=("$f"); fi
    done
  fi
fi

if [ "${#files[@]}" -eq 0 ]; then
  log "no agent configurations found, skipping"
  exit 0
fi

for f in "${files[@]}"; do
  if ! API_VERSION="$api_version" yq -e '.apiVersion == strenv(API_VERSION) and (.kind == "AgentConfig" or .kind == "CodeboxInit")' "$f" >/dev/null; then
    log "$f: expected apiVersion $api_version and kind AgentConfig"
    exit 1
  fi
done

# Maps deep-merge, arrays and scalars from later files replace earlier ones.
# shellcheck disable=SC2016
spec=$(yq eval-all -p yaml -o=json '. as $i ireduce ({}; . * $i)' "${files[@]}")

q() { jq -r "$@" <<<"$spec"; }

# Link $1 at $2 unless $2 is a real file or directory (e.g. a user's own).
link() {
  local src="$1" dest="$2"
  mkdir -p "$(dirname "$dest")"
  if [ -L "$dest" ] || [ ! -e "$dest" ]; then
    ln -sfn "$src" "$dest"
  else
    log "$dest exists and is not a symlink, skipping"
  fi
}

prune_dirs=()

link_skills() {
  local dir="$1" name src
  prune_dirs+=("$home_dir/$dir")
  while IFS=$'\t' read -r name src; do
    link "$src" "$home_dir/$dir/$name"
  done < <(q '.spec.skills.entries // {} | to_entries[] | select(.value.source != null) | [.key, .value.source] | @tsv')
}

skills_enabled=$(q '.spec.skills.enable // false')
if [ "$skills_enabled" = true ]; then
  link_skills "$(q '.spec.skills.directory // ".agents/skills"')"
fi

wrappers_dir=$(q '.spec.wrappersDirectory // ".bikeshed/bin"')
case "$wrappers_dir" in
  /*) abs_wrappers="$wrappers_dir" ;;
  *)  abs_wrappers="$home_dir/$wrappers_dir" ;;
esac

created_wrappers=()

h=""
hq() { jq -r "$@" <<<"$h"; }

while IFS= read -r name; do
  h=$(jq -c --arg n "$name" '.spec.harnesses[$n]' <<<"$spec")

  user_dir=$(hq '.userDirectory // empty')
  if [ -n "$user_dir" ]; then prune_dirs+=("$home_dir/$user_dir"); fi

  target_binary=$(hq '.wrapper.binary // .binary // .harness // empty')
  if [ -z "$target_binary" ]; then target_binary="$name"; fi

  if [ "$skills_enabled" = true ] && [ "$(hq '.linkSkills // false')" = true ]; then
    skills_dir=$(hq '.skillsDirectory // empty')
    if [ -n "$skills_dir" ]; then link_skills "$skills_dir"; fi
  fi

  if [ "$(hq '.memory.enable // false')" = true ]; then
    memory_src=$(hq '.memory.source // empty')
    memory_dir=$(hq '.memory.directory // empty')
    memory_target=$(hq '.memory.target // empty')
    if [ -n "$memory_src" ] && [ -n "$memory_dir" ] && [ -n "$memory_target" ]; then
      prune_dirs+=("$home_dir/$memory_dir")
      link "$memory_src" "$home_dir/$memory_dir/$memory_target"
    fi
  fi

  wrapper_enabled=$(hq '.wrapper.enable // true')
  if [ "$wrapper_enabled" = true ]; then
    wrapper_name=$(hq '.wrapper.name // empty')
    if [ -z "$wrapper_name" ]; then wrapper_name="$name"; fi
    wrapper_file="$abs_wrappers/$wrapper_name"

    mkdir -p "$abs_wrappers"
    created_wrappers+=("$wrapper_file")

    if [ -e "$wrapper_file" ] && ! grep -E -q "# Generated by bikeshed (activate-agent-configuration|codebox-init)" "$wrapper_file" 2>/dev/null; then
      log "$wrapper_file exists and was not generated by activate-agent-configuration, skipping"
    else
      extra_args=()
      while IFS= read -r arg; do
        if [ -n "$arg" ]; then extra_args+=("$arg"); fi
      done < <(hq '.wrapper.args // [] | .[]')

      init_extra=$(hq '.wrapper.initExtra // empty')

      {
        echo '#!/usr/bin/env bash'
        echo '# Generated by bikeshed activate-agent-configuration'
        echo 'set -e'
        while IFS=$'\t' read -r var_k var_v; do
          if [ -n "$var_k" ]; then
            escaped_v="${var_v//\"/\\\"}"
            echo "export $var_k=\"$escaped_v\""
          fi
        done < <(hq '(.wrapper.sessionVariables // .sessionVariables // {}) | to_entries[] | [.key, .value] | @tsv')

        if [ -n "$init_extra" ]; then
          echo "$init_extra"
        fi

        exec_args=()
        for a in "${extra_args[@]}"; do
          exec_args+=("\"$a\"")
        done
        exec_args+=('"$@"')
        args_str="${exec_args[*]}"

        if [[ "$target_binary" == /* ]]; then
          echo "exec \"$target_binary\" $args_str"
        else
          # shellcheck disable=SC2016
          echo 'self=$(readlink -f "$0" 2>/dev/null || realpath "$0" 2>/dev/null || echo "$0")'
          echo 'target=""'
          echo "while IFS= read -r p; do"
          # shellcheck disable=SC2016
          echo '  p_real=$(readlink -f "$p" 2>/dev/null || realpath "$p" 2>/dev/null || echo "$p")'
          # shellcheck disable=SC2016
          echo '  if [ "$p_real" != "$self" ]; then'
          # shellcheck disable=SC2016
          echo '    target="$p"'
          echo '    break'
          echo '  fi'
          echo "done < <(type -aP \"$target_binary\")"
          # shellcheck disable=SC2016
          echo 'if [ -n "$target" ]; then'
          echo "  exec \"\$target\" $args_str"
          echo 'else'
          echo "  echo \"$target_binary: command not found\" >&2"
          echo '  exit 127'
          echo 'fi'
        fi
      } > "$wrapper_file.tmp"

      mv -f "$wrapper_file.tmp" "$wrapper_file"
      chmod +x "$wrapper_file"
    fi
  fi

  ops=$(mktemp)

  mcp_target=$(hq '.mcp.target // empty')
  if [ -n "$mcp_target" ] && [ "$(hq '(.mcp.servers // {}) | length')" != 0 ]; then
    # `merge` replaces individual servers, `replace` the whole top-level key.
    jq -c '(.mcp.servers // {}) as $s
      | if (.mcp.strategy // "merge") == "merge"
        then [$s | to_entries[] | .key as $k | .value | to_entries[] | {path: [$k, .key], value: .value, strategy: "replace"}]
        else [$s | to_entries[] | {path: [.key], value: .value, strategy: "replace"}]
        end' <<<"$h" >"$ops"
    bikeshed-config-merge "$home_dir/$mcp_target" "$ops"
  fi

  settings_target=$(hq '.settings.target // empty')
  if [ -n "$settings_target" ] && [ "$(hq '(.settings.entries // {}) | length')" != 0 ]; then
    # Keyed by dotted path; applied in path order so parents precede children.
    jq -c '[.settings.entries | to_entries | sort_by(.key)[] | select(.value.value != null)
      | {path: (.key | split(".")), value: .value.value, strategy: (.value.strategy // "merge")}]' <<<"$h" >"$ops"
    bikeshed-config-merge "$home_dir/$settings_target" "$ops"
  fi

  rm -f "$ops"
done < <(q '.spec.harnesses // {} | to_entries[] | select(.value.enable == true) | .key')

# Prune wrappers left by harnesses that are no longer enabled
if [ -d "$abs_wrappers" ]; then
  for f in "$abs_wrappers"/*; do
    if [ -f "$f" ] && grep -E -q "# Generated by bikeshed (activate-agent-configuration|codebox-init)" "$f" 2>/dev/null; then
      keep=false
      for w in "${created_wrappers[@]}"; do
        if [ "$f" = "$w" ]; then keep=true; break; fi
      done
      if [ "$keep" = false ]; then
        rm -f "$f"
      fi
    fi
  done
fi

# Drop links left dangling by an earlier version.
for d in "${prune_dirs[@]}"; do
  if [ -d "$d" ]; then find "$d" -maxdepth 1 -xtype l -delete; fi
done
